/// ai_quiz_round1.dart — 对拍练习第一轮：预测输出题
///
/// 对应实践指南二第五部分步骤三与作业任务 4。
/// 出题范围（按要求指定）：空安全、命名参数、整除。
///
/// 流程：先出题 → 本人手写预测答案 → 运行核对 → 记录分歧。
///
/// 【重要写法说明】
/// 本题集刻意把所有可空值都做成**函数参数**传入，而不是在函数内部
/// `String? x;` 这样声明。原因是：若在函数内声明后立刻使用，Dart 的
/// 流分析已知它必然是 null，会报 `dead_code`（`?.` 右侧永远不执行）
/// 与 `invalid_null_aware_operator` 之类的告警。
/// 改成参数传入后，编译器无法预知实参，`?.`、`??`、`!` 才会真实参与运行期判断。
library;

// ============================================================
// 第 1 题（空安全 · ?. 与 ?? 的组合）
//   预测下面五个表达式分别输出什么？
// ============================================================
void q1(String? a, String? b) {
  print('第1题');
  print('  (1) a?.length            = ${a?.length}'); // 预测：null
  print('  (2) b?.length            = ${b?.length}'); // 预测：4
  print('  (3) a?.length ?? -1      = ${a?.length ?? -1}'); // 预测：-1
  print('  (4) b?.length ?? -1      = ${b?.length ?? -1}'); // 预测：4
  print('  (5) a ?? b ?? "fallback" = ${a ?? b ?? 'fallback'}'); // 预测：dart
}

// ============================================================
// 第 2 题（空安全 · ! 的运行时行为）
//   预测哪一行会抛异常？抛出的异常类型是什么？
// ============================================================
void q2(String? x, String? y) {
  print('\n第2题');

  try {
    print('  (1) x!.length        = ${x!.length}'); // 预测：x 非空时正常输出长度
  } catch (e) {
    print('  (1) 抛错：${e.runtimeType}');
  }

  try {
    print('  (2) y!.length        = ${y!.length}'); // 预测：y 为 null 时抛错
  } catch (e) {
    print('  (2) 抛错：${e.runtimeType} – $e');
  }

  print('  (3) y?.length ?? 0   = ${y?.length ?? 0}'); // 预测：0
  print('  追问：为什么 (2) 抛错而 (3) 不抛？');
  print('  答：(2) 用 ! 向编译器"保证"非空，为 null 时只能运行期抛错；');
  print('      (3) 用 ?. 与 ?? 真正处理了 null，所以安全。');
}

// ============================================================
// 第 3 题（命名参数 · 默认值与 required）
//   预测三次调用的输出分别是什么？
// ============================================================
void enroll({required String name, int age = 18, String? className}) {
  print('  $name / $age / ${className ?? '未分班'}');
}

void q3() {
  print('\n第3题');
  print('  (1) enroll(name: \'A\')');
  enroll(name: 'A'); // 预测：A / 18 / 未分班

  print('  (2) enroll(name: \'B\', age: 20)');
  enroll(name: 'B', age: 20); // 预测：B / 20 / 未分班

  print('  (3) enroll(name: \'C\', className: \'2班\', age: 19)');
  enroll(name: 'C', className: '2班', age: 19); // 预测：C / 19 / 2班

  print('  追问：命名参数的书写顺序会影响结果吗？');
  print('  答：不会。命名参数按名字匹配，与书写顺序无关——');
  print('      这一点与位置参数不同，也是 Flutter 组件构造函数都用命名参数的原因。');
}

// ============================================================
// 第 4 题（整除 · ~/ 与 / 的区别）
//   预测每个表达式的值与运行时类型
// ============================================================
void q4() {
  print('\n第4题');
  print(
    '  (1) 7 / 2    = ${7 / 2}   （类型 ${(7 / 2).runtimeType}）',
  ); // 预测：3.5 / double
  print(
    '  (2) 7 ~/ 2   = ${7 ~/ 2}   （类型 ${(7 ~/ 2).runtimeType}）',
  ); // 预测：3 / int
  print('  (3) -7 ~/ 2  = ${-7 ~/ 2}'); // 预测：不确定是 -3 还是 -4
  print('  (4) 7 % 2    = ${7 % 2}'); // 预测：1
  print(
    '  (5) 7.0 ~/ 2 = ${7.0 ~/ 2}  （类型 ${(7.0 ~/ 2).runtimeType}）',
  ); // 预测：不确定 double 能否用 ~/
  print('  追问：为什么 7 / 2 是 3.5 而不是 3？');
  print('  答：Dart 的 / 永远返回 double；要整数结果必须显式用 ~/。');
}

// ============================================================
// 第 5 题（空安全 · ??= 与 late）
//   预测每步输出的值
// ============================================================
void q5(String? initial) {
  print('\n第5题');

  // 说明：这里刻意用 Map 元素而不是局部变量来演示 ??=。
  // 若写成 String? v = initial; v ??= 'first'; v ??= 'second';
  // 编译器在第一次 ??= 之后已知 v 非空，第二次 ??= 会被判为 dead_code 而告警。
  // Map 元素无法被类型提升（见独立研究任务 2），所以两次 ??= 都会真实参与判断。
  final box = <String, String?>{'v': initial};

  print("  (1) 初始 box['v']      = ${box['v']}"); // 预测：null
  box['v'] ??= 'first';
  print("  (2) 第一次 ??= 之后     = ${box['v']}"); // 预测：first
  box['v'] ??= 'second';
  print("  (3) 第二次 ??= 之后     = ${box['v']}"); // 预测：仍是 first

  late String token;
  token = 'tk';
  print('  (4) late 变量赋值后    = $token'); // 预测：tk
  print('  追问：late 变量不赋值就读取会怎样？');
  print('  答：抛 LateInitializationError，与 ! 抛的 _TypeError 是不同类型——');
  print('      前者是"延迟初始化未完成"，后者是"对 null 做了非空断言"。');
}

